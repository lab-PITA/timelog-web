/** ホーム画面に追加する方法（iPhone・Android） */
export function InstallGuideScreen() {
  const standalone = isStandalone();
  const ios = isIOS();
  const [canInstall, setCanInstall] = useState(!!app.installPrompt);
  useEffect(() => {
    const onReady = () => setCanInstall(!!app.installPrompt);
    window.addEventListener('timelog-installable', onReady);
    return () => window.removeEventListener('timelog-installable', onReady);
  }, []);
  const install = async () => {
    const prompt = app.installPrompt;
    if (!prompt) return;
    app.installPrompt = null;
    setCanInstall(false);
    await prompt.prompt();
  };

  const iphone = html`<h3>iPhone（Safari）</h3>
    <ol>
      <li><b>Safari</b> でこのページを開く</li>
      <li>画面下（または上）の <b>共有ボタン</b>（四角から上向きの矢印が出ているマーク）を押す。見当たらないときは、アドレス欄の右の「•••」を押してから共有を押す</li>
      <li>一覧を下へスクロールして <b>「ホーム画面に追加」</b> を押す</li>
      <li>右上の <b>「追加」</b> を押す</li>
    </ol>
    <p class="small sub">iPhone では、Safari で開いたときとホーム画面から開いたときで、データが別々に保存されます。追加したら、ホーム画面から開く方だけを使ってください。</p>`;
  const android = html`<h3>Android（Chrome）</h3>
    ${canInstall && html`<button class="install-btn" onClick=${install}>ホーム画面に追加する</button>`}
    <ol>
      <li><b>Chrome</b> でこのページを開く</li>
      <li>右上の <b>「⋮」</b>（縦に点が3つのマーク）を押す</li>
      <li><b>「ホーム画面に追加」</b> または <b>「アプリをインストール」</b> を押す</li>
      <li>確認が出たら <b>「インストール」</b>（または「追加」）を押す</li>
    </ol>`;

  return html`<div class="screen">
    <${TopBar} title="ホーム画面に追加" onBack=${app.back} />
    <div class="scroll guide">
      ${standalone
        ? html`<p class="guide-ok">このタイムログは、ホーム画面から開かれています。設定は済んでいます。</p>`
        : html`<p>ホーム画面に追加すると、ふつうのアプリのようにアイコンから開けるようになり、インターネットがなくても使えます。</p>`}
      <h3>なぜ追加するのがよいか</h3>
      <p>ブラウザ（特に iPhone の Safari）は、しばらく開かなかったサイトのデータを自動で消すことがあります。ホーム画面に追加して使うと、記録が消えにくくなります。</p>
      ${ios ? html`${iphone}${android}` : html`${android}${iphone}`}
      <h3>注意</h3>
      <ul>
        <li>データはこの端末の中だけに保存されます。ときどき「設定」→「データの書き出し」でバックアップを取っておくと安心です。</li>
      </ul>
    </div>
  </div>`;
}
