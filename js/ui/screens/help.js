// 使い方の案内：初めて開いたときの簡単な説明、設定から開く詳しい使い方、ホーム画面に追加する方法
import { html, useState, useEffect } from '../../vendor/preact-htm.js';
import { app } from '../context.js';
import { TopBar, Dialog } from '../components.js';
import { isIOS } from './settings.js';

const isStandalone = () => window.matchMedia('(display-mode: standalone)').matches || navigator.standalone === true;

/** 初めて開いたときに1回だけ出す、簡単な使い方 */
export function IntroDialog({ onClose }) {
  return html`<${Dialog} title="タイムログへようこそ" buttons=${[{ text: 'はじめる', bold: true, onClick: onClose }]}>
    <p>「何を」「何分」したかを、かんたんに記録して振り返るアプリです。</p>
    <ol class="intro-steps">
      <li><b>記録</b>タブで、やったこと（勉強など）を選ぶ</li>
      <li>テンキーで、何分やったかを入れる</li>
      <li><b>OK</b> を押すと、ちょうど今終わったものとして記録されます</li>
    </ol>
    <p>記録は<b>今日</b>・<b>週間</b>タブでグラフになり、<b>目標</b>タブでは1週間の目標を立てられます。項目は記録タブ右上の鉛筆マークから変えられます。</p>
    <p>データはこの端末の中だけに保存されます。ホーム画面に追加すると、アプリのように使えます。</p>
    <p class="intro-more">詳しい使い方は、<b>設定</b>タブ（右下の「•••」）→<b>「使い方」</b>からいつでも確認できます。</p>
  <//>`;
}

/** 折りたたみの見出しつきの段落 */
function Section({ title, open = false, children }) {
  return html`<details class="help-section" open=${open}>
    <summary>${title}</summary>
    <div class="help-body">${children}</div>
  </details>`;
}

